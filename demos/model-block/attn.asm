CONFIG eps_rms 1e-5
IN X AS F:HW
IN WQ AS F:HW
IN WK AS F:HW
IN WV AS F:HW
IN WO AS F:HW
IN R1 AS F:SEQ
IN R2 AS F:SEQ
N1 = RMSNORM(X, R1)
Q = MATMUL(N1, WQ)
K = MATMUL(N1, WK)
V = MATMUL(N1, WV)
KT = TRANSPOSE(K)
S = MATMUL(Q, KT)
P = SOFTMAX(S)
A = MATMUL(P, V)
O = MATMUL(A, WO)
RES = ADD(X, O)
N2 = RMSNORM(RES, R2)
