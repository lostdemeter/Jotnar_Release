CONFIG eps_rms 1e-5
IN X AS F:HW
IN WQ AS F:HW
IN WK AS F:HW
IN WV AS F:HW
IN WO AS F:HW
IN R1 AS F:SEQ
IN R2 AS F:SEQ
N1 = RMSNORM(X, R1)
Q = MATMUL(N1, WQ)
K = MATMUL(N1, WK)
V = MATMUL(N1, WV)
Q0 = SLICE(Q, 1, 0, 16)
K0 = SLICE(K, 1, 0, 16)
V0 = SLICE(V, 1, 0, 16)
Q1 = SLICE(Q, 1, 16, 32)
K1 = SLICE(K, 1, 16, 32)
V1 = SLICE(V, 1, 16, 32)
Q2 = SLICE(Q, 1, 32, 48)
K2 = SLICE(K, 1, 32, 48)
V2 = SLICE(V, 1, 32, 48)
Q3 = SLICE(Q, 1, 48, 64)
K3 = SLICE(K, 1, 48, 64)
V3 = SLICE(V, 1, 48, 64)
KT0 = TRANSPOSE(K0)
KT1 = TRANSPOSE(K1)
KT2 = TRANSPOSE(K2)
KT3 = TRANSPOSE(K3)
S0 = MATMUL(Q0, KT0)
S1 = MATMUL(Q1, KT1)
S2 = MATMUL(Q2, KT2)
S3 = MATMUL(Q3, KT3)
P0 = SOFTMAX(S0)
P1 = SOFTMAX(S1)
P2 = SOFTMAX(S2)
P3 = SOFTMAX(S3)
A0 = MATMUL(P0, V0)
A1 = MATMUL(P1, V1)
A2 = MATMUL(P2, V2)
A3 = MATMUL(P3, V3)
C0 = CONCAT(A0, A1, 1)
C1 = CONCAT(C0, A2, 1)
C = CONCAT(C1, A3, 1)
O = MATMUL(C, WO)
RES = ADD(X, O)
N2 = RMSNORM(RES, R2)
