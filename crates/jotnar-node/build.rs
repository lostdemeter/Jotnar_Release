//! Build-time emission for the JotnarOS system modules.
//!
//! M8 lowers the scalar integer modules under
//! `build/rootfs/usr/local/share/jotnar/modules/` into Rust step functions and
//! one `SystemModule` enum. Unsupported operations fail loudly; this is the v1
//! emission subset, not a general compiler.

use std::collections::HashMap;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

use jotnar::asm::{self, AsmOptions};
use jotnar::ir::BoundProgram;
use jotnar::payload::{self, Feeds};
use jotnar::value::Value;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let base = manifest_dir.join("image/rootfs/usr/local/share/jotnar/modules");
    println!("cargo:rerun-if-changed={}", base.display());

    let mut entries: Vec<(String, PathBuf)> = fs::read_dir(&base)
        .unwrap_or_else(|e| panic!("read modules dir {}: {e}", base.display()))
        .flatten()
        .filter_map(|e| {
            let p = e.path();
            if p.join("manifest.json").exists() {
                let name = p
                    .file_name()
                    .and_then(|s| s.to_str())
                    .map(|s| s.to_string());
                name.map(|n| (n, p))
            } else {
                None
            }
        })
        .collect();
    entries.sort_by(|a, b| a.0.cmp(&b.0));

    let mut modules = Vec::new();
    for (name, dir) in &entries {
        println!("cargo:rerun-if-changed={}", dir.join("manifest.json").display());
        println!("cargo:rerun-if-changed={}", dir.join("policy.asm").display());
        let listing = fs::read_to_string(dir.join("policy.asm"))
            .unwrap_or_else(|e| panic!("read {}/policy.asm: {e}", dir.display()));
        let bound = asm::assemble(&listing, &AsmOptions::new(dir.to_string_lossy().as_ref()))
            .unwrap_or_else(|e| panic!("assemble {name}: {e}"));
        let seed = load_seed(&dir.join("seed.json"));
        let struct_name = camel(name);
        let code = emit_module(&struct_name, &bound, &seed);
        modules.push((name.clone(), struct_name, code));
    }

    let mut out = String::new();
    out.push_str("// generated by node/build.rs (M8 system modules)\n");
    for (_, _, code) in &modules {
        out.push_str(code);
        out.push('\n');
    }
    out.push_str("pub const NAMES: &[&str] = &[");
    for (i, (name, _, _)) in modules.iter().enumerate() {
        if i > 0 {
            out.push_str(", ");
        }
        out.push_str(&format!("{name:?}"));
    }
    out.push_str("];\n\n");

    out.push_str("pub enum SystemModule {\n");
    for (_, struct_name, _) in &modules {
        out.push_str(&format!("    {struct_name}({struct_name}),\n"));
    }
    out.push_str("}\n\n");

    out.push_str("impl SystemModule {\n");
    out.push_str("    pub fn new(name: &str) -> Option<Self> {\n        match name {\n");
    for (name, struct_name, _) in &modules {
        out.push_str(&format!(
            "            {name:?} => Some(Self::{struct_name}({struct_name}::new())),\n"
        ));
    }
    out.push_str("            _ => None,\n        }\n    }\n\n");
    out.push_str("    pub fn name(&self) -> &'static str {\n        match self {\n");
    for (name, struct_name, _) in &modules {
        out.push_str(&format!("            Self::{struct_name}(_) => {name:?},\n"));
    }
    out.push_str("        }\n    }\n\n");
    out.push_str("    pub fn step(&mut self, event: i64) -> i64 {\n        match self {\n");
    for (_, struct_name, _) in &modules {
        out.push_str(&format!("            Self::{struct_name}(m) => m.step(event),\n"));
    }
    out.push_str("        }\n    }\n\n");
    out.push_str("    pub fn actions(&self) -> i64 {\n        match self {\n");
    for (_, struct_name, _) in &modules {
        out.push_str(&format!("            Self::{struct_name}(m) => m.actions(),\n"));
    }
    out.push_str("        }\n    }\n\n");
    out.push_str("    pub fn set_actions(&mut self, n: i64) {\n        match self {\n");
    for (_, struct_name, _) in &modules {
        out.push_str(&format!("            Self::{struct_name}(m) => m.set_actions(n),\n"));
    }
    out.push_str("        }\n    }\n\n");
    out.push_str("    pub fn state_json(&self) -> serde_json::Value {\n        match self {\n");
    for (_, struct_name, _) in &modules {
        out.push_str(&format!("            Self::{struct_name}(m) => m.state_json(),\n"));
    }
    out.push_str("        }\n    }\n}\n");

    let out_path = PathBuf::from(env::var("OUT_DIR").unwrap()).join("system_modules.rs");
    fs::write(&out_path, out).unwrap_or_else(|e| panic!("write generated system: {e}"));
}

fn load_seed(path: &Path) -> Feeds {
    if !path.exists() {
        return Feeds::new();
    }
    payload::read_payload(path).unwrap_or_else(|e| panic!("read seed: {e}"))
}

fn camel(name: &str) -> String {
    name.split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|s| !s.is_empty())
        .map(|s| {
            let mut chars = s.chars();
            match chars.next() {
                Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

fn snake(name: &str) -> String {
    let mut out = String::new();
    let mut prev_lower = false;
    for c in name.chars() {
        if c.is_ascii_uppercase() {
            if prev_lower && !out.ends_with('_') {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
            prev_lower = false;
        } else if c.is_ascii_alphanumeric() || c == '_' {
            out.push(c);
            prev_lower = c.is_ascii_lowercase() || c.is_ascii_digit();
        } else {
            out.push('_');
            prev_lower = false;
        }
    }
    out
}

fn state_init(seed: &Feeds, name: &str) -> i64 {
    match seed.get(name) {
        Some(Value::I64(a)) => a.iter().next().copied().unwrap_or(0),
        None => 0,
        Some(_) => panic!("state '{name}' seed must be I64 scalar"),
    }
}

fn render_arg(arg: &str, vars: &HashMap<String, String>) -> String {
    if let Ok(n) = arg.parse::<i64>() {
        return n.to_string();
    }
    vars.get(arg)
        .cloned()
        .unwrap_or_else(|| panic!("unknown scalar arg '{arg}'"))
}

fn render_op(mn: &str, a: &str, b: &str) -> String {
    match mn {
        "IADD" => format!("({a} + {b})"),
        "ISUB" => format!("({a} - {b})"),
        "IMUL" => format!("({a} * {b})"),
        "IAND" => format!("({a} & {b})"),
        "IOR" => format!("({a} | {b})"),
        "IXOR" => format!("({a} ^ {b})"),
        "IMAX" => format!("if {a} >= {b} {{ {a} }} else {{ {b} }}"),
        "IMIN" => format!("if {a} <= {b} {{ {a} }} else {{ {b} }}"),
        "IEQ" => format!("if {a} == {b} {{ 1 }} else {{ 0 }}"),
        "ILT" => format!("if {a} < {b} {{ 1 }} else {{ 0 }}"),
        other => panic!("emitter v1 does not support op {other} (fail loud)"),
    }
}

fn emit_module(struct_name: &str, bound: &BoundProgram, seed: &Feeds) -> String {
    let state: Vec<String> = bound.state.clone();
    let mut vars: HashMap<String, String> = HashMap::new();

    let mut args = Vec::new();
    for decl in &bound.inputs {
        if state.iter().any(|s| s == &decl.name) {
            let field = snake(&decl.name);
            vars.insert(decl.name.clone(), format!("{field}_in"));
        } else {
            let field = snake(&decl.name);
            vars.insert(decl.name.clone(), field.clone());
            args.push(format!("{field}: i64"));
        }
    }
    for s in &state {
        let field = snake(s);
        vars.insert(s.clone(), format!("{field}_in"));
    }

    let mut body = String::new();
    for s in &state {
        let field = snake(s);
        body.push_str(&format!("        let {field}_in: i64 = self.{field};\n"));
    }

    let mut temp = 0usize;
    for ins in &bound.instrs {
        if ins.is_repeat() || ins.is_end() || ins.is_break() {
            panic!("emitter v1 does not support control flow ({})", ins.mn);
        }
        if ins.outs.len() != 1 {
            panic!("emitter v1 expects one output per instruction ({})", ins.line);
        }
        let expr = if ins.mn == "ISELECT" {
            if ins.args.len() != 3 {
                panic!("ISELECT expects three args ({})", ins.line);
            }
            let p = render_arg(&ins.args[0], &vars);
            let a = render_arg(&ins.args[1], &vars);
            let b = render_arg(&ins.args[2], &vars);
            format!("if {p} != 0 {{ {a} }} else {{ {b} }}")
        } else {
            if ins.args.len() != 2 {
                panic!("emitter v1 expects binary ops ({})", ins.line);
            }
            let a = render_arg(&ins.args[0], &vars);
            let b = render_arg(&ins.args[1], &vars);
            render_op(&ins.mn, &a, &b)
        };
        let var = format!("t{temp}");
        temp += 1;
        body.push_str(&format!("        let {var}: i64 = {expr};\n"));
        vars.insert(ins.outs[0].clone(), var);
    }
    for s in &state {
        let field = snake(s);
        let expr = vars
            .get(s)
            .cloned()
            .unwrap_or_else(|| panic!("state '{s}' not assigned"));
        body.push_str(&format!("        self.{field} = {expr};\n"));
    }
    if !vars.contains_key("ACTION") {
        panic!("emitter v1 requires an ACTION output");
    }
    let action = vars.get("ACTION").cloned().unwrap();

    let fields: Vec<String> = state.iter().map(|s| format!("pub {}: i64", snake(s))).collect();
    let init: Vec<String> = state
        .iter()
        .map(|s| format!("{}: {}", snake(s), state_init(seed, s)))
        .collect();
    let actions = if state.iter().any(|s| s == "ACTIONS") {
        "self.actions".to_string()
    } else {
        "0".to_string()
    };
    let set_actions = if state.iter().any(|s| s == "ACTIONS") {
        "self.actions = n;".to_string()
    } else {
        "let _ = n;".to_string()
    };
    let state_json = if state.is_empty() {
        "serde_json::json!({})".to_string()
    } else {
        let mut entries = Vec::new();
        for s in &state {
            let field = snake(s);
            entries.push(format!(
                "{:?}: serde_json::json!({{\"kind\":\"I64\",\"shape\":[1],\"data\":[self.{}.to_string()]}})",
                s, field
            ));
        }
        format!("serde_json::json!({{{}}})", entries.join(", "))
    };

    format!(
        "#[derive(Clone, Debug)]\n\
         pub struct {struct_name} {{\n    {fields}\n}}\n\
         \n\
         impl {struct_name} {{\n\
         \x20   pub fn new() -> Self {{ Self {{ {init} }} }}\n\
         \x20   pub fn step(&mut self, {args}) -> i64 {{\n{body}\
         \x20       {action}\n\
         \x20   }}\n\
         \x20   pub fn actions(&self) -> i64 {{ {actions} }}\n\
         \x20   pub fn set_actions(&mut self, n: i64) {{ {set_actions} }}\n\
         \x20   pub fn state_json(&self) -> serde_json::Value {{ {state_json} }}\n\
         }}\n",
        fields = fields.join(" "),
        init = init.join(", "),
        args = args.join(", "),
        body = body,
        action = action,
    )
}
